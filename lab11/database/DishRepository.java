package lab11.database;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import lab6.dishes.HotDish;

/** Виконує всі SQL-операції над єдиною таблицею dishes. */
public class DishRepository {
    private static final String CREATE_TABLE_SQL =
            "CREATE TABLE IF NOT EXISTS dishes ("
                    + "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "name VARCHAR(100) NOT NULL, "
                    + "preparation_time_minutes INTEGER NOT NULL, "
                    + "serving_temperature_celsius DOUBLE PRECISION NOT NULL, "
                    + "cooking_method VARCHAR(100) NOT NULL, "
                    + "CONSTRAINT uq_dishes_name UNIQUE (name), "
                    + "CONSTRAINT chk_dishes_name CHECK (CHAR_LENGTH(TRIM(name)) > 0), "
                    + "CONSTRAINT chk_dishes_time CHECK (preparation_time_minutes BETWEEN 0 AND 1440), "
                    + "CONSTRAINT chk_dishes_temperature "
                    + "CHECK (serving_temperature_celsius BETWEEN -50 AND 150), "
                    + "CONSTRAINT chk_dishes_method "
                    + "CHECK (CHAR_LENGTH(TRIM(cooking_method)) > 0)"
                    + ")";

    private static final String INSERT_SQL =
            "INSERT INTO dishes "
                    + "(name, preparation_time_minutes, serving_temperature_celsius, cooking_method) "
                    + "VALUES (?, ?, ?, ?)";

    private final DishDatabase database;

    public DishRepository(DishDatabase database) {
        if (database == null) {
            throw new IllegalArgumentException("База даних не може бути null.");
        }
        this.database = database;
    }

    /** Створює таблицю з первинним ключем, унікальністю та CHECK-обмеженнями. */
    public void initializeSchema() throws SQLException {
        try (Connection connection = database.openConnection();
                Statement statement = connection.createStatement()) {
            statement.executeUpdate(CREATE_TABLE_SQL);
        }
    }

    /** Під час першого запуску заповнює БД десятьма об'єктами з попередніх ЛР. */
    public boolean seedIfEmpty() throws SQLException {
        try (Connection connection = database.openConnection()) {
            if (countRecords(connection) > 0) {
                return false;
            }

            connection.setAutoCommit(false);
            try (PreparedStatement statement = connection.prepareStatement(INSERT_SQL)) {
                for (HotDish dish : createInitialDishes()) {
                    setDishParameters(statement, dish);
                    statement.addBatch();
                }
                statement.executeBatch();
                connection.commit();
                return true;
            } catch (SQLException exception) {
                connection.rollback();
                throw exception;
            } finally {
                connection.setAutoCommit(true);
            }
        }
    }

    public List<DishRecord> findAll() throws SQLException {
        return executeSelection(
                "SELECT id, name, preparation_time_minutes, "
                        + "serving_temperature_celsius, cooking_method "
                        + "FROM dishes ORDER BY id",
                null);
    }

    /** Вибірка за умовою: час приготування не перевищує задану кількість хвилин. */
    public List<DishRecord> findPreparedWithin(final int maximumMinutes) throws SQLException {
        return executeSelection(
                "SELECT id, name, preparation_time_minutes, "
                        + "serving_temperature_celsius, cooking_method "
                        + "FROM dishes WHERE preparation_time_minutes <= ? "
                        + "ORDER BY preparation_time_minutes, name",
                new StatementConfigurer() {
                    @Override
                    public void configure(PreparedStatement statement) throws SQLException {
                        statement.setInt(1, maximumMinutes);
                    }
                });
    }

    public DishRecord findById(int id) throws SQLException {
        List<DishRecord> records = executeSelection(
                "SELECT id, name, preparation_time_minutes, "
                        + "serving_temperature_celsius, cooking_method "
                        + "FROM dishes WHERE id = ?",
                new IdConfigurer(id));
        return records.isEmpty() ? null : records.get(0);
    }

    public int insert(HotDish dish) throws SQLException {
        try (Connection connection = database.openConnection();
                PreparedStatement statement = connection.prepareStatement(
                        INSERT_SQL, Statement.RETURN_GENERATED_KEYS)) {
            setDishParameters(statement, dish);
            statement.executeUpdate();

            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    return keys.getInt(1);
                }
            }
        }
        throw new SQLException("Сервер не повернув ID нового запису.");
    }

    public boolean update(int id, HotDish dish) throws SQLException {
        String sql = "UPDATE dishes SET name = ?, preparation_time_minutes = ?, "
                + "serving_temperature_celsius = ?, cooking_method = ? WHERE id = ?";
        try (Connection connection = database.openConnection();
                PreparedStatement statement = connection.prepareStatement(sql)) {
            setDishParameters(statement, dish);
            statement.setInt(5, id);
            return statement.executeUpdate() == 1;
        }
    }

    public boolean delete(int id) throws SQLException {
        try (Connection connection = database.openConnection();
                PreparedStatement statement = connection.prepareStatement(
                        "DELETE FROM dishes WHERE id = ?")) {
            statement.setInt(1, id);
            return statement.executeUpdate() == 1;
        }
    }

    private List<DishRecord> executeSelection(
            String sql,
            StatementConfigurer configurer) throws SQLException {
        List<DishRecord> records = new ArrayList<DishRecord>();
        try (Connection connection = database.openConnection();
                PreparedStatement statement = connection.prepareStatement(sql)) {
            if (configurer != null) {
                configurer.configure(statement);
            }
            try (ResultSet resultSet = statement.executeQuery()) {
                while (resultSet.next()) {
                    HotDish dish = new HotDish(
                            resultSet.getString("name"),
                            resultSet.getInt("preparation_time_minutes"),
                            resultSet.getDouble("serving_temperature_celsius"),
                            resultSet.getString("cooking_method"));
                    records.add(new DishRecord(resultSet.getInt("id"), dish));
                }
            }
        }
        return records;
    }

    private static int countRecords(Connection connection) throws SQLException {
        try (Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery("SELECT COUNT(*) FROM dishes")) {
            resultSet.next();
            return resultSet.getInt(1);
        }
    }

    private static void setDishParameters(PreparedStatement statement, HotDish dish)
            throws SQLException {
        statement.setString(1, dish.getName());
        statement.setInt(2, dish.getPreparationTimeMinutes());
        statement.setDouble(3, dish.getServingTemperatureCelsius());
        statement.setString(4, dish.getCookingMethod());
    }

    private static HotDish[] createInitialDishes() {
        return new HotDish[] {
            new HotDish("Український борщ", 60, 70.0, "Варіння"),
            new HotDish("Овочевий суп", 35, 68.0, "Варіння"),
            new HotDish("Картопляне пюре", 30, 60.0, "Варіння"),
            new HotDish("Куряча відбивна", 25, 65.0, "Смаження"),
            new HotDish("Гречана каша", 20, 62.0, "Варіння"),
            new HotDish("Овочеве рагу", 45, 67.0, "Тушкування"),
            new HotDish("Запечена риба", 50, 64.0, "Запікання"),
            new HotDish("Сирники", 25, 58.0, "Смаження"),
            new HotDish("Плов", 55, 69.0, "Тушкування"),
            new HotDish("Вареники", 40, 63.0, "Варіння")
        };
    }

    private interface StatementConfigurer {
        void configure(PreparedStatement statement) throws SQLException;
    }

    private static class IdConfigurer implements StatementConfigurer {
        private final int id;

        IdConfigurer(int id) {
            this.id = id;
        }

        @Override
        public void configure(PreparedStatement statement) throws SQLException {
            statement.setInt(1, id);
        }
    }
}
